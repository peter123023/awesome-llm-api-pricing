function priceTable(lang) {
  const t = I18N[lang];
  const fmt = lang === 'zh' ? fmtPrice : fmtPriceEn;
  const lines = [];
  lines.push('| ' + t.th.join(' | ') + ' |');
  lines.push('|' + ' --- |'.repeat(t.th.length));
  for (const cat of sortedCats) {
    for (const it of byCat.get(cat.id) || []) {
      for (const p of it.pricing) {
        lines.push(
          `| **[${it.name[lang === 'zh' ? 'zh' : 'en']}](${it.url})** | ${p.model} | ${fmt(p.input, it.currency)} | ${fmt(p.output, it.currency)} | ${p.context} | [${lang === 'zh' ? '定价页' : 'page'}](${it.url}) |`
        );
      }
    }
  }
  return lines.join('\n');
}

function providerSections(lang) {
  const t = I18N[lang];
  const L = lang === 'zh' ? 'zh' : 'en';
  const out = [];
  for (const cat of sortedCats) {
    out.push(`### ${cat.name[L]}`);
    out.push('');
    for (const it of byCat.get(cat.id) || []) {
      const note = t.notes(it);
      out.push(
        `- **[${it.name[L]}](${it.url})** — ${it.desc[L]} · [${lang === 'zh' ? '官网' : 'website'}](${originOf(it.url)})${note ? `（${note}）` : ''}`
      );
    }
    out.push('');
  }
  return out.join('\n');
}

function tocLines(lang) {
  const t = I18N[lang];
  const L = lang === 'zh' ? 'zh' : 'en';
  const anchor = (heading) => '](#' + slugify(heading.replace(/^##\s*/, '')) + ')';
  const lines = ['- [' + (lang === 'zh' ? '收录范围' : 'Scope') + anchor(t.scope)];
  lines.push('- [' + (lang === 'zh' ? '价格对比总表' : 'Price Comparison') + anchor(t.tableH));
  lines.push('- [' + (lang === 'zh' ? '厂商明细' : 'Providers') + anchor(t.providersH));
  for (const cat of sortedCats) {
    lines.push('  - [' + cat.name[L] + '](#' + slugify(cat.name[L]) + ')');
  }
  lines.push('- ' + t.more);
  lines.push('  - [' + (lang === 'zh' ? '关于本清单' : 'About') + anchor(t.about));
  lines.push('  - [' + (lang === 'zh' ? '数据与更新' : 'Data & Updates') + anchor(t.dataH));
  lines.push('  - [' + (lang === 'zh' ? '参与贡献' : 'Contributing') + anchor(t.contrib));
  lines.push('  - [' + (lang === 'zh' ? '许可证' : 'License') + anchor(t.license));
  return lines.join('\n');
}

function build(lang) {
  const t = I18N[lang];
  return [
    t.switchLine,
    '',
    t.h1,
    '',
    t.tagline,
    '',
    badges,
    '',
    '---',
    '',
    t.toc,
    '',
    tocLines(lang),
    '',
    '---',
    '',
    t.scope,
    '',
    t.scopeBody,
    '',
    t.tableH,
    '',
    t.tableNote,
    '',
    priceTable(lang),
    '',
    t.providersH,
    '',
    providerSections(lang),
    '---',
    '',
    t.about,
    '',
    t.aboutBody,
    '',
    t.dataH,
    '',
    t.dataBody,
    '',
    t.contrib,
    '',
    t.contribBody,
    '',
    t.license,
    '',
    t.licenseBody,
    '',
  ].join('\n');
}

