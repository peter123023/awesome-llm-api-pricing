// CSV 导出
const csvHeader = ['slug', 'vendor', 'category', 'model', 'currency', 'input_per_1m', 'output_per_1m', 'context', 'pricing_url'];
const esc = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
const rows = [csvHeader.join(',')];
for (const it of items) {
  for (const p of it.pricing) {
    rows.push([
      it.slug, it.name.en, it.category, p.model, it.currency,
      p.input ?? '', p.output ?? '', p.context ?? '', it.url,
    ].map(esc).join(','));
  }
}
writeFileSync(join(root, 'data/items.csv'), rows.join('\n') + '\n');

