import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = process.env.REPO || 'peter123023/awesome-llm-api-pricing';

const categories = JSON.parse(readFileSync(join(root, 'data/categories.json'), 'utf8'));
const data = JSON.parse(readFileSync(join(root, 'data/items.json'), 'utf8'));
const items = data.items;

// GitHub 官方锚点算法：先删标点，再把每个空格逐个换成 -（不折叠）
// 见 https://github.com/... 本仓库 SKILL 坑点 #1
const slugify = (t) =>
  t.toLowerCase().trim()
    .replace(/[\u2000-\u206F\u2E00-\u2E7F\\'!"#$%&()*+,./:;<=>?@[\]^`{|}~]/g, '')
    .replace(/ /g, '-');

const originOf = (url) => {
  try { return new URL(url).origin; } catch { return url; }
};

const sym = (c) => c === 'CNY' ? '¥' : '$';

function fmtPrice(v, currency) {
  if (v === null || v === undefined) return '—';
  if (v === 0) return '免费';
  return `${sym(currency)}${v}`;
}
function fmtPriceEn(v, currency) {
  if (v === null || v === undefined) return '—';
  if (v === 0) return 'Free';
  return `${sym(currency)}${v}`;
}

// 按 category 分组，按 categories.json 的 order 排序
const catOrder = Object.fromEntries(categories.map((c, i) => [c.id, i]));
const byCat = new Map();
for (const it of items) {
  if (!byCat.has(it.category)) byCat.set(it.category, []);
  byCat.get(it.category).push(it);
}
const sortedCats = [...categories].sort((a, b) => catOrder[a.id] - catOrder[b.id]);

